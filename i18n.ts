export type Language = "en" | "hi";

export const getTranslation = (lang: Language, path: string): string => {
  const keys = path.split(".");
  let value: any = translations[lang];

  for (const key of keys) {
    value = value?.[key];
    if (!value) return path;
  }

  return value;
};
